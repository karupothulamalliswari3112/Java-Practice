package day02_operators;

public class AssignmentDemo {
	public static void main(String[] args) {
	int a=5;
	System.out.println(a);
	a += 3;
	System.out.println("After +3 :"+a);
	a -= 2;
	System.out.println("After -2 :"+a);
	a *= 5;
	System.out.println("After *5 :"+a);
	a /= 2;
	System.out.println("After /2 :"+a);
	a %= 2;
	System.out.println("After %2 :"+a);

}
}
