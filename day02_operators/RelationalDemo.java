package day02_operators;

public class RelationalDemo {
	public static void main(String[] args) {
		int a=3; 
		int b=2;
		System.out.println("a="+a + " b="+b);
		
		System.out.println("a==b:"+(a==b));
		
		System.out.println("a!=b:"+(a!=b));
		
		System.out.println("a>=b:"+(a>=b));
		
		System.out.println("a<=b:"+(a<=b));
		
		System.out.println("a>b:"+(a>b));
		
		System.out.println("a<b:"+(a<b));
		
		}
}
